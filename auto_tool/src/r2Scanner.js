        "                r.frames.push(fc.toDataURL('image/jpeg', CFG.jpegQ).split(',')[1]);",
        "            }",
        "        }",
        "    }",
        "",
        "    const result = {",
        "        v: 1, source: 'r2-handtrack', scanId: CFG.scanId || null,",
        "        videoFingerprint: videoFingerprint || null, sensitivityPreset: CFG.sensitivityPreset || 'balanced',",
